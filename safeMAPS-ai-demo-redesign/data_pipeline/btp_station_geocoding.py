def resolve_station(raw_name: str):
    """Return (canonical_key, lat, lon, display_name), or None if unmapped."""
    key = STATION_ALIASES.get(raw_name.strip().lower())
    if key is None:
        return None
    lat, lon, display = STATION_COORDS[key]
    return key, lat, lon, display
